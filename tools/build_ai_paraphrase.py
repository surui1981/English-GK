BATCHES.append(BATCH6)


def main():
    existing = {}
    if os.path.exists(OUT):
        prev = json.load(open(OUT, encoding='utf-8'))
        existing = {w['w']: w for w in prev.get('words', [])}

    for batch in BATCHES:
        for hw, senses in batch.items():
            existing[hw] = OrderedDict([
                ('w', hw),
                ('senses', [OrderedDict([('pos', p), ('meaning', m), ('collocation', c)])
                            for p, m, c in senses]),
                ('source', '自研释义改写（模型逐词产出）'),
            ])

    words = [existing[k] for k in sorted(existing)]

    # 必考层总数与待补齐名单从覆盖层真实读取，避免统计写死。
    coverage_path = os.path.join(ROOT, 'data', 'product', 'word_coverage.json')
    required = []
    if os.path.exists(coverage_path):
        coverage = json.load(open(coverage_path, encoding='utf-8'))
        required = [w['w'] for w in coverage.get('words', []) if w.get('tier') == 'required']
    required_total = len(required) or 443
    missing = [w for w in required if w not in existing]

    result = OrderedDict([
        ('meta', OrderedDict([
            ('name', '必考层 · 自研释义改写'),
            ('method', '模型逐词产出的中文释义改写：更换措辞、按高考常见用法重组，附典型搭配。非教材原文照搬。'),
            ('coverage', OrderedDict([
                ('paraphrased_words', len(words)),
                ('required_layer_total', required_total),
                ('remaining_in_required', len(missing)),
            ])),
            ('note', '按批追加 BATCHES 覆盖全部必考层；当前剩余 %d 词待改写。' % len(missing)),
        ])),
        ('words', words),
    ])
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8') as f:
        json.dump(result, f, ensure_ascii=False, indent=1)
    print('自研释义改写：%d 词；必考层 %d 词，待补 %d 词' %
          (len(words), required_total, len(missing)))


if __name__ == '__main__':
    main()
